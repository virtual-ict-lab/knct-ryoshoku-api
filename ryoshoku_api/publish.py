"""Build a complete static generation from saved data, without fetching or OCR."""
from datetime import datetime
import json
import logging
import re
import os
import uuid
from pathlib import Path, PurePosixPath
import shutil
import tempfile
from zoneinfo import ZoneInfo
import pdfplumber
from ryoshoku_ocr.config import PROJECT_ROOT
from ryoshoku_ocr.menu import require, valid_date, validate_cache
from ryoshoku_ocr.store import atomic_json
from .archive import Archive, archive_path, select_menus

log = logging.getLogger('api.publish')


def date_in_japan(instant=None):
    instant = instant or datetime.now(ZoneInfo('Asia/Tokyo'))
    require(instant.tzinfo is not None, 'Publication timestamp needs a timezone')
    return instant.astimezone(ZoneInfo('Asia/Tokyo')).date().isoformat()


def metadata(entry):
    if entry is None:
        return None
    return dict(startDate=entry['start_date'], endDate=entry['end_date'], sourceSha256=entry['sha256'], pdf=entry['path'], json=str(PurePosixPath(entry['path']).with_suffix('.json')))


def prune_generations(directory, keep):
    keep = {path.resolve() for path in keep if path is not None}
    for path in directory.iterdir():
        if path.is_symlink() or not re.fullmatch('[a-f0-9]{32}', path.name) or path.resolve() in keep:
            continue
        if not path.is_dir() or not (path / '.ryoshoku-api').is_file():
            continue
        try:
            shutil.rmtree(path)
        except OSError:
            log.warning('Could not remove superseded publication %s', path, exc_info=True)


def publish(config, *, today=None, instant=None):
    output = config.public_dir
    backup = output.with_name('.' + output.name + '.previous')
    # Recover legacy two-rename publications before reading/validating history.
    if not output.exists() and not output.is_symlink() and backup.exists():
        backup.rename(output)
    today = today or date_in_japan(instant)
    valid_date(today)
    archive = Archive(config)
    state = archive.load()
    require(bool(state['menus']), 'No archived menus to publish')
    selection = select_menus(state['menus'], today)
    # Validate every snapshot before touching the active publication.
    menus = {entry['sha256']: archive.menu(entry) for entry in state['menus']}
    preferred = [entry for entry in state['menus'] if entry['preferred']]
    weeks = [menus[entry['sha256']] for entry in sorted(preferred, key=lambda e:e['start_date'], reverse=True)[:32]]
    api = validate_cache({'schemaVersion': 1, 'weeks': weeks})
    api.update(sourceUrl=state['source_url'], publishedForDate=today, current=metadata(selection['current']), upcoming=metadata(selection['upcoming']))
    latest = next((e for e in state['menus'] if e['sha256'] == state.get('latest_pdf_hash')), None)
    require(latest is not None, 'Latest official PDF is missing from archive')
    index = {**state, 'latest_pdf_path': 'latest.pdf', 'latest_week_start': latest['start_date'], 'latest_week_end': latest['end_date']}
    output.parent.mkdir(parents=True, exist_ok=True)
    generations = output.with_name('.' + output.name + '-generations')
    generations.mkdir(exist_ok=True)
    if output.is_symlink():
        require(output.resolve().is_relative_to(generations.resolve()) and (output / '.ryoshoku-api').is_file(), 'PUBLIC_DIR points outside owned generations')
    else:
        require(not output.exists() or (output / '.ryoshoku-api').exists() or not any(output.iterdir()), 'PUBLIC_DIR contains files not generated by this application')
    previous_generation = output.resolve() if output.is_symlink() else None
    with tempfile.TemporaryDirectory(prefix='.building-', dir=generations) as temporary:
        staging = Path(temporary)
        shutil.copytree(PROJECT_ROOT / 'site', staging, dirs_exist_ok=True)
        (staging / '.nojekyll').touch()
        (staging / '.ryoshoku-api').touch()
        for entry in state['menus']:
            target = staging / str(archive_path(entry['path']))
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(archive.snapshot(entry['sha256']) / 'source.pdf', target)
            atomic_json(target.with_suffix('.json'), menus[entry['sha256']])
        if selection['current'] is not None:
            shutil.copyfile(archive.snapshot(selection['current']['sha256']) / 'source.pdf', staging / 'kondate.pdf')
            with pdfplumber.open(staging / 'kondate.pdf') as pdf:
                with pdf.pages[0].to_image(resolution=300, antialias=True).original as image:
                    image.save(staging / 'kondate.png', format='PNG', dpi=(300, 300))
        shutil.copyfile(archive.snapshot(latest['sha256']) / 'source.pdf', staging / 'latest.pdf')
        atomic_json(staging / 'kondate.json', api)
        atomic_json(staging / 'state.json', index)
        generation = generations / uuid.uuid4().hex
        staging.rename(generation)
        pointer = output.with_name('.' + output.name + '-link-' + uuid.uuid4().hex)
        try:
            pointer.symlink_to(os.path.relpath(generation, output.parent), target_is_directory=True)
            if output.exists() and not output.is_symlink():
                if backup.exists():
                    shutil.rmtree(backup)
                output.rename(backup)
            try:
                # One atomic pointer swap; existing readers retain their
                # immutable generation. Uploaded Pages files contain no links.
                pointer.replace(output)
            except BaseException:
                if not output.exists() and backup.exists():
                    backup.rename(output)
                raise
            if backup.exists():
                shutil.rmtree(backup)
        finally:
            pointer.unlink(missing_ok=True)
    # Open file descriptors remain readable after unlinking on supported POSIX hosts.
    prune_generations(generations, {generation, previous_generation})
    return api
